"""Hotspot anchors: the outermost point of each structure, facing away from the model's vertical axis.

A label then shows on whichever side of the model its structure is on (model-viewer hides a hotspot
whose normal points away from the camera). Structures sitting on the axis, and every structure of a
slender model like the spine column, get a zero normal, which model-viewer treats as visible from every side.

Re-anchor existing packs from their GLB:  python anchors.py ../spine ../heart ../digestive
"""
import sys
import numpy as np

ON_AXIS = 0.15  # offset from the axis, as a fraction of the model's horizontal radius
SLENDER = 0.12  # horizontal radius / height below which the model is a column, labelled all around


def anchor(v: np.ndarray, center_xz: np.ndarray, radius: float, slender: bool = False) -> tuple[list[float], list[float]]:
    b0, b1 = v.min(0), v.max(0)
    cy, h = (b0[1] + b1[1]) / 2, b1[1] - b0[1]
    band = np.where(np.abs(v[:, 1] - cy) <= max(h * 0.15, 0.003))[0]
    off = v[:, [0, 2]].mean(0) - center_xz
    if slender or np.linalg.norm(off) < ON_AXIS * radius:
        i = band[np.argmax(v[band, 2])]  # front-most point, always visible
        return [round(float(x), 4) for x in v[i]], [0.0, 0.0, 0.0]
    d = off / np.linalg.norm(off)
    i = band[np.argmax(v[band][:, [0, 2]] @ d)]
    return [round(float(x), 4) for x in v[i]], [round(float(d[0]), 4), 0.0, round(float(d[1]), 4)]


def model_frame(vertex_sets: list[np.ndarray]) -> tuple[np.ndarray, float, bool]:
    allv = np.vstack(vertex_sets)
    lo, hi = allv.min(0), allv.max(0)
    radius = float((hi - lo)[[0, 2]].max() / 2)
    return (lo + hi)[[0, 2]] / 2, radius, radius / float(hi[1] - lo[1]) < SLENDER


def reanchor(pack: str) -> None:
    import glob, trimesh, yaml
    glb = glob.glob(f"{pack}/assets/*.glb")[0]
    scene = trimesh.load(glb, force="scene")
    meshes = {}
    for node in scene.graph.nodes_geometry:
        tf, geom = scene.graph[node]
        meshes[node] = scene.geometry[geom].copy().apply_transform(tf)
    center, radius, slender = model_frame([m.vertices for m in meshes.values()])
    path = f"{pack}/hotspots.yaml"
    lines = open(path, encoding="utf-8").read().splitlines()
    header = [l for l in lines if l.startswith("#")]
    out = header[:1] + ["# Generated by content/_tools/anchors.py: outermost point of each node at mid-height, normal facing away",
                        "# from the model's vertical axis (zero normal = on the axis, visible from every side).",
                        "# Use as data-position / data-normal on hotspot buttons."]
    for h in yaml.safe_load("\n".join(lines)) or []:
        m = meshes.get(h["mesh_name"])
        if m is None:
            print(f"  {pack}: no mesh {h['mesh_name']}, kept as is")
            p, n = h["position"], h["normal"]
        else:
            pos, nrm = anchor(np.asarray(m.vertices), center, radius, slender)
            p, n = " ".join(f"{x}m" for x in pos), " ".join(str(x) for x in nrm)
        out += [f"- structure_id: {h['structure_id']}", f"  mesh_name: {h['mesh_name']}",
                f"  position: \"{p}\"", f"  normal: \"{n}\""]
    open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"{path}: {len(meshes)} meshes re-anchored{' (slender: labelled all around)' if slender else ''}")


if __name__ == "__main__":
    for p in sys.argv[1:]:
        reanchor(p)
